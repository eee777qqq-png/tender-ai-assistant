"""Извлечение обычного текста из .pdf-приложения документации закупки —
аналог `docx_reader.extract_text_from_docx()`, но для PDF (найдено вживую
2026-09-26: 35 из 63 реальных приложений «Требования к заявке» — .pdf, не
.docx, см. CLAUDE.md, открытый п.3).

**Только PDF с текстовым слоем.** `pypdf` умеет доставать только тот текст,
что реально закодирован в файле как текст — если приложение представляет
собой скан (изображение страницы без текстового слоя), `extract_text()`
на такой странице вернёт пустую строку, и эта функция вернёт пустой текст
(или почти пустой) целиком — не ошибку и не "текст не найден", просто
честно мало/ничего. Различить два случая ("документ короткий, но с
текстом" и "документ длинный, но это скан") можно по числу страниц vs
длине извлечённого текста — сам этот модуль такую проверку не делает,
только достаёт то, что есть; вызывающий код (или эксперт) должен заметить
несоответствие. Настоящий OCR (например, `pytesseract` поверх
отрендеренных страниц) — не реализован, отдельная и более дорогая задача,
не в скоупе этого модуля."""

from __future__ import annotations

import io

from pypdf import PdfReader

from .errors import AttachmentParseError


def extract_text_from_pdf(content: bytes) -> str:
    """Текст всех страниц PDF, через двойной перевод строки между
    страницами. Пустая строка для каждой конкретной страницы (в том числе
    из-за отсутствия текстового слоя — скан) просто ничего не добавляет,
    без исключения."""
    # Проверено на практике (2026-10-03), что реально бросает pypdf:
    # случайные байты и усечённый файл — `PdfStreamError`; пустой —
    # `EmptyFileError`; без структуры (`%PDF` без xref) — `PdfReadError`;
    # зашифрованный с непустым паролем — `FileNotDecryptedError`; AES без
    # установленного `cryptography` — `DependencyError`. На испорченных
    # потоках страниц бывают и обычные ValueError/KeyError/struct.error, так
    # что ловим широко. PDF, зашифрованный пустым паролем, pypdf открывает
    # сам. Скан без текстового слоя — не ошибка (см. докстринг модуля).
    try:
        reader = PdfReader(io.BytesIO(content))
        parts: list[str] = []
        for page in reader.pages:
            text = (page.extract_text() or "").strip()
            if text:
                parts.append(text)
    except Exception as exc:  # noqa: BLE001
        raise AttachmentParseError(f"не удалось открыть .pdf: {type(exc).__name__}: {exc}") from exc

    return "\n\n".join(parts)
