"""Генерация черновика содержания п.1/п.5 ст.43 44-ФЗ (сведения об участнике
закупки + стандартные декларации) как .docx — единственная содержательная
генерация документов, которую Агент 6 сегодня делает (см. CLAUDE.md,
открытый п.2).

**Не «заявка по единой форме» — единой федеральной формы не существует.**
Ст. 43 44-ФЗ задаёт только обязательное СОДЕРЖАНИЕ заявки (п.1, подп. а-р —
сведения об участнике; п.2 — предложение по объекту закупки; п.3 —
предложение о цене); саму ФОРМУ оформления устанавливает каждый заказчик в
документации к своей закупке (подтверждено 2026-09-27 — см. CLAUDE.md).
Старая двухчастная схема аукциона («часть 1»/«часть 2» по ст.66) и
Постановление №1401, где она была отражена в типовой форме, утратили силу
с 01.01.2022 — этот генератор их не воспроизводит и не должен.

Генерируется только то, что механически следует из `ClientProfile` — без
домысливания. Что здесь НЕ генерируется (см. `document_assembler.models.
ManualSection`, `assembler.py`): предложение по объекту закупки (п.2 —
требует знания технического задания конкретной закупки, риск несоответствия
документации) и предложение о цене (п.3 — бизнес-решение собственника).
"""

from __future__ import annotations

import io

from docx import Document

from classifier.tender import Tender
from onboarding.models import ClientProfile

# Примерная форма декларации о соответствии единым требованиям — закон не
# устанавливает обязательную форму (см. CLAUDE.md, открытый п.2, со ссылкой
# на base.garant.ru/55730088 — «примерная форма», допускается свободная).
# Текст ниже — стандартная формулировка по существу требований ч.1 ст.31
# 44-ФЗ (правоспособность, отсутствие ликвидации/банкротства/приостановки
# деятельности, отсутствие в реестре недобросовестных поставщиков,
# отсутствие ограничений для офшорных компаний, отсутствие конфликта
# интересов) — одинаковая для любого участника, поэтому механическая
# подстановка организации/даты в неё не является домысливанием.
_UNIFIED_REQUIREMENTS_DECLARATION_TEMPLATE = (
    "Настоящим {org_name} (ИНН {inn}, ОГРН/ОГРНИП {ogrn}) подтверждает "
    "соответствие единым требованиям, установленным частью 1 статьи 31 "
    "Федерального закона от 05.04.2013 № 44-ФЗ, а именно:\n"
    "1) соответствие требованиям, установленным в соответствии с "
    "законодательством Российской Федерации к лицам, осуществляющим "
    "поставку товара, выполнение работы, оказание услуги, являющихся "
    "объектом закупки;\n"
    "2) неприменение в отношении участника закупки процедуры ликвидации "
    "юридического лица, отсутствие решения арбитражного суда о признании "
    "участника закупки несостоятельным (банкротом) и об открытии "
    "конкурсного производства;\n"
    "3) неприменение в отношении участника закупки административного "
    "наказания в виде приостановления деятельности на дату подачи заявки;\n"
    "4) отсутствие у участника закупки недоимки по налогам, сборам, "
    "задолженности по иным обязательным платежам в бюджеты бюджетной "
    "системы Российской Федерации в размере, установленном законом;\n"
    "5) отсутствие у участника закупки — физического лица либо у "
    "руководителя, членов коллегиального исполнительного органа, лица, "
    "исполняющего функции единоличного исполнительного органа, или "
    "главного бухгалтера юридического лица — судимости за преступления в "
    "сфере экономики и (или) преступления, предусмотренные статьями 289, "
    "290, 291, 291.1 Уголовного кодекса Российской Федерации;\n"
    "6) отсутствие фактов конфликта интересов между участником закупки и "
    "заказчиком;\n"
    "7) участник закупки не является офшорной компанией;\n"
    "8) отсутствие у участника закупки ограничений для участия в закупках, "
    "предусмотренных законодательством Российской Федерации."
)

_PERSONAL_DATA_CONSENT_TEMPLATE = (
    "Настоящим {contact_person}, действующий в качестве контактного лица "
    "{org_name}, даёт согласие на обработку своих персональных данных "
    "(фамилия, имя, отчество, номер телефона, адрес электронной почты) "
    "заказчиком и оператором электронной площадки в целях, связанных с "
    "участием {org_name} в закупке {purchase_number}, в соответствии с "
    "Федеральным законом от 27.07.2006 № 152-ФЗ «О персональных данных»."
)

_SMP_DECLARATION_TEMPLATE = (
    "Настоящим {org_name} (ИНН {inn}) заявляет о своей принадлежности к "
    "субъектам малого предпринимательства в соответствии с частью 3 статьи "
    "30 Федерального закона от 05.04.2013 № 44-ФЗ и Федеральным законом от "
    "24.07.2007 № 209-ФЗ «О развитии малого и среднего предпринимательства "
    "в Российской Федерации»."
)


def generate_participant_info_docx(profile: ClientProfile, tender: Tender) -> bytes:
    """Черновик содержания п.1/п.5 ст.43 44-ФЗ — сведения об участнике
    закупки и стандартные декларации, полностью из `ClientProfile`.

    `profile.legal.is_smp` — единственное поле, для которого честный ответ
    может быть «не указано» (`None`): в этом случае раздел про декларацию
    СМП/СОНКО в документе явно помечен как требующий уточнения, а не
    подставлена ни заведомо ложная декларация, ни пустой раздел без
    объяснения."""
    document = Document()

    document.add_heading("Сведения об участнике закупки и декларации", level=1)
    document.add_paragraph(
        "Черновик содержания п. 1 и п. 5 статьи 43 Федерального закона от "
        "05.04.2013 № 44-ФЗ — не заявка по единой форме: единой федеральной "
        "формы заявки не существует, форму устанавливает заказчик в "
        "документации конкретной закупки. Перед подачей проверьте и "
        "приведите в соответствие с требованиями документации именно этой "
        "закупки."
    )
    document.add_paragraph(
        f"Закупка: {tender.purchase_number} — {tender.name}"
    )
    document.add_paragraph(f"Заказчик: {tender.customer_name}")

    document.add_heading("Сведения об участнике закупки (п. 1 ст. 43 44-ФЗ)", level=2)
    table = document.add_table(rows=0, cols=2)
    table.style = "Table Grid"

    def add_row(label: str, value: str) -> None:
        row = table.add_row().cells
        row[0].text = label
        row[1].text = value if value else "(не указано в профиле)"

    add_row("Наименование организации", profile.legal.org_name)
    add_row("ИНН", profile.legal.inn)
    add_row("ОГРН/ОГРНИП", profile.legal.ogrn)
    add_row("Юридический адрес", profile.legal.legal_address)
    add_row("Контактное лицо", profile.legal.contact_person)
    add_row("Телефон", profile.legal.phone)
    add_row("Email", profile.legal.email)

    document.add_heading(
        "Декларация о соответствии единым требованиям (ч. 1 ст. 31 44-ФЗ)", level=2
    )
    document.add_paragraph(
        _UNIFIED_REQUIREMENTS_DECLARATION_TEMPLATE.format(
            org_name=profile.legal.org_name or "(наименование не указано в профиле)",
            inn=profile.legal.inn or "(не указан)",
            ogrn=profile.legal.ogrn or "(не указан)",
        )
    )

    document.add_heading(
        "Декларация о принадлежности к субъектам малого предпринимательства "
        "(п. 5 ст. 43 44-ФЗ)",
        level=2,
    )
    if profile.legal.is_smp is None:
        document.add_paragraph(
            "ТРЕБУЕТ УТОЧНЕНИЯ: принадлежность к СМП/СОНКО не указана в "
            "профиле клиента (ClientProfile.legal.is_smp). Уточните у "
            "клиента и заполните профиль, прежде чем подавать эту "
            "декларацию — по умолчанию она не подставляется."
        )
    elif profile.legal.is_smp:
        document.add_paragraph(
            _SMP_DECLARATION_TEMPLATE.format(
                org_name=profile.legal.org_name or "(наименование не указано в профиле)",
                inn=profile.legal.inn or "(не указан)",
            )
        )
    else:
        document.add_paragraph(
            "По данным профиля клиента, участник не относится к субъектам "
            "малого предпринимательства — декларация не требуется, если "
            "закупка не предполагает иного."
        )

    document.add_heading("Согласие на обработку персональных данных", level=2)
    document.add_paragraph(
        _PERSONAL_DATA_CONSENT_TEMPLATE.format(
            contact_person=profile.legal.contact_person or "(контактное лицо не указано в профиле)",
            org_name=profile.legal.org_name or "(наименование не указано в профиле)",
            purchase_number=tender.purchase_number,
        )
    )

    buffer = io.BytesIO()
    document.save(buffer)
    return buffer.getvalue()
