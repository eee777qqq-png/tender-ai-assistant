"""Заготовка пакета документов (Агент 6 — Сборщик документов).

`fields` — список того, какие поля пакета нужны для подачи заявки и откуда
каждое берётся: из профиля клиента (Агент 11), данных закупки (Агент 2) или
извлечённых Агентом 3 требований документации (сроки, обеспечение, допуски).

С 2026-09-27 это не только каркас — `participant_info_docx` несёт реально
сгенерированный черновик содержания п.1/п.5 ст.43 44-ФЗ (сведения об
участнике + декларации, `docx_generator.generate_participant_info_docx()`),
а `manual_sections` явно перечисляет то, что Агент 6 сознательно не
генерирует (п.2/п.3 той же статьи — предложение по объекту закупки и по
цене, см. CLAUDE.md, открытый п.2, и докстринг `ManualSection` ниже)."""

from __future__ import annotations

from dataclasses import dataclass, field

from document_analyst.models import HiddenRisk


@dataclass
class PackageField:
    """Одно поле будущего пакета документов."""

    name: str
    source: str  # путь к полю-источнику, например "legal.inn" или "tender.max_price"
    value: str
    status: str  # "ready" | "missing" | "not_applicable"
    required: bool = True  # обязательно ли поле для этой конкретной закупки


@dataclass
class ManualSection:
    """Часть заявки, которую Агент 6 сознательно НЕ генерирует — не пустая
    заглушка и не правдоподобный, но непроверенный текст, а явная пометка
    "нужен человек".

    По ст. 43 44-ФЗ (действующая статья про заявку на участие в закупке;
    старая двухчастная схема аукциона по ст.66 утратила силу с 01.01.2022 —
    см. CLAUDE.md, открытый п.2) генерации без риска подходит только п.1/п.5
    (сведения об участнике + декларации, механическая подстановка из
    `ClientProfile`, см. `docx_generator.generate_participant_info_docx`).
    П.2 (предложение по объекту закупки) требует знания конкретного ТЗ
    закупки, которое Агент 3 сейчас не извлекает в пригодном виде; п.3
    (предложение о цене) — бизнес-решение собственника, не факт из профиля.
    Оба попадают сюда, не в `fields` (те — про комплектность данных, эти —
    про то, что данных в принципе не может быть без участия человека)."""

    name: str
    article_reference: str  # например, "ст.43 п.2 44-ФЗ"
    note: str


@dataclass
class DocumentPackage:
    """Заготовка пакета документов для конкретной пары клиент+закупка."""

    client_id: str
    tender_purchase_number: str
    fields: list[PackageField] = field(default_factory=list)
    # Скрытые риски от Агента 3 — информационно, для будущего Агента 8
    # (консультант для клиента). Намеренно не часть `fields`: не участвует
    # в проверке комплектности (Агент 7 смотрит только `fields`), поэтому
    # ничего не блокирует по построению, а не по соглашению об именовании.
    hidden_risks: list[HiddenRisk] = field(default_factory=list)
    # Сгенерированный черновик содержания п.1/п.5 ст.43 44-ФЗ (сведения об
    # участнике + декларации) — байты .docx, не путь к файлу: вызывающий код
    # сам решает, куда и как его сохранить (CLAUDE.md, открытый п.2, закрыт
    # 2026-09-27 для этой механической части). `None`, если не сгенерирован
    # (например, вызывающий код запросил только заготовку полей).
    participant_info_docx: bytes | None = None
    # Части заявки, для которых генерация текста сознательно не реализована —
    # см. докстринг `ManualSection`. Не участвует в `check_completeness()`
    # (Агент 7 смотрит только `fields`) — это отдельный, явный список для
    # человека, не критерий комплектности данных профиля.
    manual_sections: list[ManualSection] = field(default_factory=list)

    def missing_fields(self) -> list[PackageField]:
        return [f for f in self.fields if f.status == "missing"]

    def is_complete(self) -> bool:
        """Все применимые поля заполнены (не значит, что пакет готов к отправке —
        содержательная проверка эксперта всё равно обязательна по протоколу)."""
        return len(self.missing_fields()) == 0
