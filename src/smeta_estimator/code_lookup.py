"""Прямой поиск кандидата по коду из колонки "Обоснование" готовой сметы —
не текстовым поиском по названию.

**Почему это отдельный, более надёжный путь для одного конкретного
сценария.** Круг 2 бенчмарка Агента 4 (2026-09-29, см. CLAUDE.md, открытый
п.17) — построчная сверка на двух реальных ЛСР показала: основная причина
переоценки была не в качестве текстового поиска (`search.py`), а в
произвольном выборе между несколькими кандидатами с ОДИНАКОВЫМ
`match_score` — притом что правильный код часто был среди топ-3, просто не
первым. Когда смета уже составлена экспертом-сметчиком, код нормы ГЭСН/
ГЭСНр или ресурса ФСБЦ уже стоит в документе (колонка "Обоснование") — для
ПЕРЕПРОВЕРКИ такой сметы искать его текстом бессмысленно и менее надёжно,
чем найти напрямую.

**Это не замена текстовому поиску, а приоритетный путь перед ним.**
Текстовый поиск (`search_candidates`/`search_material_candidates`) по-прежнему
нужен для другого сценария — когда Агент 4 составляет смету С НУЛЯ по
ведомости объёмов работ, где готового кода ещё нет. `estimate_smeta_document.py`
пробует этот путь первым, только когда у строки есть `WorkVolumeRow.code`,
и переходит к текстовому поиску, если код не распознан или не нашёлся ни в
одном из двух каталогов — поведение для строк без кода не меняется вообще.
"""

from __future__ import annotations

import re

from .models import GesnWorkItem, MaterialCandidateInfo

# Убираем всё, что не буква/цифра/точка/дефис — пробелы между префиксом
# ("ГЭСНр", "ГЭСН") и числом, неразрывные пробелы и т.п. Коды материалов
# ФСБЦ (вида "08.3.05.05-0053") пробелов не содержат вообще, поэтому для
# них это no-op.
_STRIP_RE = re.compile(r"[^\w.\-]+", re.UNICODE)

# Каталог ГЭСНр хранит код С ПРИСТАВКОЙ ("ГЭСНр68-02-004-04", без пробела —
# см. fsnb_parser.parse_gesn_xml(apply_code_prefix=True)). Базовый каталог
# ГЭСН хранит код БЕЗ приставки вообще ("01-02-057-02") — в самой смете
# перед этими кодами в колонке "Обоснование" эксперт обычно пишет "ГЭСН "
# как пояснение, не как часть кода, и её нужно снять, а не оставить.
# Приставки ГЭСНр и ГЭСНм (монтаж оборудования, подключён 2026-10-03)
# хранятся в каталоге как часть кода — без снятия; проверяются ДО общей
# "ГЭСН", иначе "ГЭСНм10-08-002-02" превратился бы в "м10-08-002-02".
_KEPT_PREFIXES = ("ГЭСНр", "ГЭСНм")
_GESN_PREFIX = "ГЭСН"

# Каталог материалов ФСБЦ хранит код БЕЗ приставки ("11.1.03.01-0065") — но
# ГРАНД-Смета (круг 1 бенчмарка, 2026-09-29, документы "roof"/"ceiling",
# №0373100025626000005/№0373100025726000259) пишет в "Обоснование" код с
# приставкой "ФСБЦ-", которую раньше ничего не снимало (в отличие от
# ГЭСН/ГЭСНр) — из-за этого точный поиск по коду материала не срабатывал
# НИ РАЗУ ни на одном материальном ресурсе обоих документов круга 1 (0 из
# 8 материалов с этой приставкой), несмотря на то, что сам код был верным.
_FSBC_PREFIX = "ФСБЦ-"


def normalize_gesn_code(raw: str) -> str:
    """Приводит сырой текст колонки "Обоснование" к тому же виду, в котором
    код хранится в каталоге (см. докстринг модуля). Пустая строка на входе
    даёт пустую строку на выходе — вызывающий код сам решает, что делать с
    "кода нет".

    **Берётся только первая строка ячейки, остальное отбрасывается.**
    Найдено на том же документе "roof": ГРАНД-Смета иногда дописывает в ту
    же ячейку, через перенос строки, название файла-источника текущей цены
    (например, "ФСБЦ-11.1.03.01-0065\\nСплит-форма город Москва на 3
    квартал 2026 года.xlsx") — без этой отсечки старый код просто склеивал
    всё в один мусорный токен ("...0065Сплит-формагородМосквана...xlsx"),
    который не мог совпасть ни с одним кодом каталога."""
    first_line = raw.strip().splitlines()[0] if raw.strip() else ""
    compact = _STRIP_RE.sub("", first_line)
    if compact.startswith(_KEPT_PREFIXES):
        return compact
    if compact.startswith(_GESN_PREFIX):
        return compact[len(_GESN_PREFIX):]
    if compact.startswith(_FSBC_PREFIX):
        return compact[len(_FSBC_PREFIX):]
    return compact


def find_exact_work_candidate(catalog: list[GesnWorkItem], raw_code: str) -> GesnWorkItem | None:
    """Точное совпадение по коду в каталоге работ ГЭСН/ГЭСНр. `None` — код
    не распознан (пустой после нормализации) или не нашёлся в каталоге,
    вызывающий код должен упасть на текстовый поиск, не считать это ошибкой."""
    code = normalize_gesn_code(raw_code)
    if not code:
        return None
    for item in catalog:
        if item.code == code:
            return item
    return None


def find_exact_material_candidate(
    catalog: list[MaterialCandidateInfo], raw_code: str
) -> MaterialCandidateInfo | None:
    """То же самое для каталога материалов ФСБЦ — коды там уже без пробелов
    в исходном виде (например, "08.3.05.05-0053"), но нормализация всё
    равно применяется на случай случайного пробела при копировании из
    Excel."""
    code = normalize_gesn_code(raw_code)
    if not code:
        return None
    for item in catalog:
        if item.code == code:
            return item
    return None


# Маркеры "Обоснования", которые НЕ являются кодом каталога ГЭСН/ГЭСНр/ФСБЦ
# в принципе — найдено при разборе круга 1 бенчмарка (2026-09-30, документ
# ceiling): 9 из 19 строк документа не находят ни одного кандидата текстовым
# поиском, и все 9 попадают в один из этих классов, не в "поиск не
# справился". Различие важно эксперту — "снята рыночная котировка" и
# "каталог ГЭСНм не подключён" требуют разных действий, ни одно не решается
# ослаблением порога MATCH_SCORE_THRESHOLD (это дало бы мусорные совпадения
# на настоящих пробелах поиска, см. докстринг search.py).
_MARKET_QUOTE_PREFIX = "ТЦ_"  # "текущая цена" по конкретной котировке поставщика
_GESNM_PREFIX = "ГЭСНм"  # каталог ГЭСНм подключён 2026-10-03; сюда попадает только код, которого в нём нет
_ORDER_REFERENCE_MARKER = "пр_"  # ссылка на пункт приказа/методику (например "421/пр_2020_п.75_пп.а"), не код позиции
_TRANSPORT_KEYWORDS = ("погрузк", "перевозк")  # тарифы на транспорт/погрузку — не в ГЭСН/ФСБЦ, см. CLAUDE.md открытый п.17


def classify_unresolved_row(code: str | None, name: str) -> str | None:
    """Для строки ведомости, у которой текстовый поиск не нашёл ни одного
    кандидата (`MATCH_SCORE_THRESHOLD` не пройден никем) — определяет,
    относится ли она к одному из уже известных классов "это в принципе не
    код сметного каталога", а не к "поиск не справился". Возвращает `None`,
    если ни один известный класс не подошёл — тогда причина остаётся общей
    ("score ниже порога"/"слов нет в каталоге"), без домысливания.

    Не решает задачу целиком (для рыночных позиций и транспортных тарифов
    по-прежнему нет автоматической цены) — только явно называет КЛАСС
    причины, чтобы эксперт не тратил время на разбор одной и той же
    находки заново на каждом документе."""
    raw = code or ""
    if raw.startswith(_MARKET_QUOTE_PREFIX):
        return "рыночная котировка конкретного поставщика (ТЦ_) — не позиция сметного каталога, нужна отдельная рыночная цена"
    if raw.startswith(_GESNM_PREFIX):
        return "код ГЭСНм не найден в подключённом каталоге ГЭСНм (возможно, устаревший/нестандартный шифр или сборник ГЭСНмр)"
    if _ORDER_REFERENCE_MARKER in raw.lower():
        return "ссылка на пункт приказа/методику начисления, не код позиции каталога"
    lowered_name = name.lower()
    if any(keyword in lowered_name for keyword in _TRANSPORT_KEYWORDS):
        return "похоже на транспортный/тарифный справочник (погрузка/перевозка) — не в ГЭСН/ФСБЦ (известный пробел, см. CLAUDE.md)"
    return None
