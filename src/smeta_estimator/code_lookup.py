"""Прямой поиск кандидата по коду из колонки "Обоснование" готовой сметы —
не текстовым поиском по названию.

**Почему это отдельный, более надёжный путь для одного конкретного
сценария.** Круг 2 бенчмарка Агента 4 (2026-09-29, см. CLAUDE.md, открытый
п.17) — построчная сверка на двух реальных ЛСР показала: основная причина
переоценки была не в качестве текстового поиска (`search.py`), а в
произвольном выборе между несколькими кандидатами с ОДИНАКОВЫМ
`match_score` — притом что правильный код часто был среди топ-3, просто не
первым. Когда смета уже составлена экспертом-сметчиком, код нормы ГЭСН/
ГЭСНр или ресурса ФСБЦ уже стоит в документе (колонка "Обоснование") — для
ПЕРЕПРОВЕРКИ такой сметы искать его текстом бессмысленно и менее надёжно,
чем найти напрямую.

**Это не замена текстовому поиску, а приоритетный путь перед ним.**
Текстовый поиск (`search_candidates`/`search_material_candidates`) по-прежнему
нужен для другого сценария — когда Агент 4 составляет смету С НУЛЯ по
ведомости объёмов работ, где готового кода ещё нет. `estimate_smeta_document.py`
пробует этот путь первым, только когда у строки есть `WorkVolumeRow.code`,
и переходит к текстовому поиску, если код не распознан или не нашёлся ни в
одном из двух каталогов — поведение для строк без кода не меняется вообще.
"""

from __future__ import annotations

import re

from .models import GesnWorkItem, MaterialCandidateInfo

# Убираем всё, что не буква/цифра/точка/дефис — пробелы между префиксом
# ("ГЭСНр", "ГЭСН") и числом, неразрывные пробелы и т.п. Коды материалов
# ФСБЦ (вида "08.3.05.05-0053") пробелов не содержат вообще, поэтому для
# них это no-op.
_STRIP_RE = re.compile(r"[^\w.\-]+", re.UNICODE)

# Каталог ГЭСНр хранит код С ПРИСТАВКОЙ ("ГЭСНр68-02-004-04", без пробела —
# см. fsnb_parser.parse_gesn_xml(apply_code_prefix=True)). Базовый каталог
# ГЭСН хранит код БЕЗ приставки вообще ("01-02-057-02") — в самой смете
# перед этими кодами в колонке "Обоснование" эксперт обычно пишет "ГЭСН "
# как пояснение, не как часть кода, и её нужно снять, а не оставить.
_GESNR_PREFIX = "ГЭСНр"
_GESN_PREFIX = "ГЭСН"


def normalize_gesn_code(raw: str) -> str:
    """Приводит сырой текст колонки "Обоснование" к тому же виду, в котором
    код хранится в каталоге (см. докстринг модуля). Пустая строка на входе
    даёт пустую строку на выходе — вызывающий код сам решает, что делать с
    "кода нет"."""
    compact = _STRIP_RE.sub("", raw.strip())
    if compact.startswith(_GESNR_PREFIX):
        return compact
    if compact.startswith(_GESN_PREFIX):
        return compact[len(_GESN_PREFIX):]
    return compact


def find_exact_work_candidate(catalog: list[GesnWorkItem], raw_code: str) -> GesnWorkItem | None:
    """Точное совпадение по коду в каталоге работ ГЭСН/ГЭСНр. `None` — код
    не распознан (пустой после нормализации) или не нашёлся в каталоге,
    вызывающий код должен упасть на текстовый поиск, не считать это ошибкой."""
    code = normalize_gesn_code(raw_code)
    if not code:
        return None
    for item in catalog:
        if item.code == code:
            return item
    return None


def find_exact_material_candidate(
    catalog: list[MaterialCandidateInfo], raw_code: str
) -> MaterialCandidateInfo | None:
    """То же самое для каталога материалов ФСБЦ — коды там уже без пробелов
    в исходном виде (например, "08.3.05.05-0053"), но нормализация всё
    равно применяется на случай случайного пробела при копировании из
    Excel."""
    code = normalize_gesn_code(raw_code)
    if not code:
        return None
    for item in catalog:
        if item.code == code:
            return item
    return None
