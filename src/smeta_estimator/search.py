"""Простой поиск кандидатов по ключевым словам — не embeddings.

По договорённости (`docs/agent4-ai-matching-feasibility.md`): полноценный
семантический поиск можно добавить позже, для фундамента достаточно
пересечения слов запроса с названием позиции ГЭСН. Формулировки ГЭСН сильно
параметризованы — «похожий текст» не гарантия «тот самый код», поэтому
результат — всегда список кандидатов на выбор эксперта, не единственный
ответ (см. `models.MatchResult`).

`search_material_candidates()` — тот же принцип, применённый к каталогу
материалов (ФСБЦ_Мат&Оборуд), добавлен 2026-09-28: строка ведомости объёмов
работ может оказаться по сути материалом/изделием, а не нормируемой
работой (найдено на реальных сметах — «Уголок алюминиевый декоративный»,
«Светильник светодиодный...» и подобные искали по каталогу работ и
находили случайные, ничего не значащие совпадения). Использует ТОТ ЖЕ
`tokenize_words()`, что и `search_candidates()` — принципиально, не другую
функцию сопоставления (например, `text_matching.stem_words`, которая
используется в `material_candidates.py`/`work_volume_extractor.py` для
других задач): `estimate_smeta_document.py` сравнивает `match_score` из
обоих поисков напрямую, и это сравнение честно только если оценка
считается одинаково для обоих каталогов.

**Технические (цифровые) токены и почему у них НЕТ отдельного веса —
исследовано на реальных промахах круга 2, 2026-09-29 (см. CLAUDE.md,
открытый п.16.2/17, замер `--force-text-search`).** Простое
"|пересечение|/|запрос|" путало явно разные варианты внутри одной
категории (фракция щебня "20-40" vs "5-10", марка цемента "32,5Н" vs
"42,5Н", типоразмер трубы "3000" vs другой, ширина в ГЭСНр "1,75" vs "1")
— но настоящая причина оказалась не в том, что цифровой токен "весит как
обычное слово", а в том, что он **вообще не доходил до сравнения**:
фильтр `len(word) >= 3` (рассчитанный на то, чтобы выкинуть шумные
обрывки/союзы) отсеивал короткие числа («20», «40», «75», «32», «1») ещё
ДО подсчёта пересечения — «20-40» и «5(3)-10» распадались на токены
короче 3 символов и попросту исчезали из множества слов обеих сторон, так
что запрос и оба кандидата совпадали дословно (score 1.0 у обоих).
**Фикс — только это:** фильтр по длине применяется теперь лишь к токенам
БЕЗ цифры, цифровой токен остаётся в множестве при любой длине, включая
однозначные («1», «2» и т.п.).

**Отдельно проверено и ОТКЛОНЕНО (не на глаз, прогоном на обоих реальных
документах круга 2 целиком, все 42 строки с известным эталонным кодом) —
дополнительный ВЕС для технического токена (×2/×3/×5) поверх этого фикса.**
Интуиция была: несовпадение цифры должно штрафовать сильнее, чем
несовпадение обычного слова — но на полном каталоге (34004 работы + 45847
материалов, не выдуманных 2 примера) это систематически СНИЖАЛО точность
относительно простого фикса без веса:

| Вариант | Точность (42 строки, оба документа) |
|---|---|
| Было (короткие цифры отсекались, без веса) | 57,1% |
| **Фикс длины токена, БЕЗ доп. веса (текущая реализация)** | **66,7%** |
| Вес ×3, с однозначными цифрами | 52,4% (хуже, чем «было») |
| Вес ×3, только числа от 2 цифр | 54,8% |
| Вес ×2, только числа от 2 цифр | 66,7% (не хуже, но и не лучше) |
| Вес ×2, с однозначными цифрами | 57,1% |
| Вес ×5, только числа от 2 цифр | 50,0% |

Причина вреда: однозначные цифры («2» — группа грунта, «1» — количество и
т.п.) крайне частые и почти всегда СЛУЧАЙНО совпадают с несвязанными
позициями каталога — вес усиливал именно этот шум, а не сигнал. Числа от
2 цифр с весом ×2 не вредили, но и не улучшали результат относительно
полного отсутствия веса — усложнение без пользы. Вывод: сам факт, что
технический токен участвует в сравнении (не отсекается длиной), уже даёт
весь измеримый эффект — отдельный множитель не нужен."""

from __future__ import annotations

import re

from .models import GesnWorkItem, MaterialCandidateInfo, MaterialRateCandidate, RateCandidate

_WORD_RE = re.compile(r"[а-яёa-z0-9]+", re.IGNORECASE)
_STOPWORDS = {"и", "в", "с", "со", "на", "из", "для", "по", "к", "от", "не", "или", "при", "без"}
_DIGIT_RE = re.compile(r"\d")


def tokenize_words(text: str) -> set[str]:
    """Токен без цифры короче 3 символов отбрасывается как шум (союзы/
    обрывки) — токен С цифрой остаётся при любой длине, включая
    однозначные («1», «2»…): именно такие токены несут различающую
    техническую информацию (фракция/марка/типоразмер/номер расценки), не
    шум, см. докстринг модуля."""
    return {
        word
        for word in (m.lower() for m in _WORD_RE.findall(text))
        if word not in _STOPWORDS and (len(word) >= 3 or _DIGIT_RE.search(word))
    }


def _overlap_score(query_tokens: set[str], item_tokens: set[str]) -> float | None:
    """Доля слов запроса, найденных в названии позиции (0..1) — простое
    "|пересечение|/|запрос|", без отдельного веса для технических токенов
    (проверено и осознанно отклонено, см. докстринг модуля — вес не
    улучшал точность на реальных документах, иногда даже вредил). `None`
    — нет вообще ни одного общего слова (такая позиция не попадает в
    выдачу совсем, не нулевой скор)."""
    overlap = query_tokens & item_tokens
    if not overlap:
        return None
    return len(overlap) / len(query_tokens)


def search_candidates(
    catalog: list[GesnWorkItem], query_text: str, top_n: int = 5
) -> list[RateCandidate]:
    """Оценка релевантности — доля слов запроса, найденных в названии
    позиции (0..1). Позиции без пересечения слов вообще не попадают в
    выдачу — не нулевой скор, а полное отсутствие в списке."""
    query_tokens = tokenize_words(query_text)
    if not query_tokens:
        return []

    scored: list[tuple[float, GesnWorkItem]] = []
    for item in catalog:
        item_tokens = tokenize_words(item.name)
        score = _overlap_score(query_tokens, item_tokens)
        if score is None:
            continue
        scored.append((score, item))

    scored.sort(key=lambda pair: pair[0], reverse=True)
    return [
        RateCandidate(
            code=item.code,
            name=item.name,
            unit=item.unit,
            base_price=item.base_price,
            match_score=score,
            resources=list(item.resources),
            unpriced_resource_codes=list(item.unpriced_resource_codes),
            abstract_resource_codes=list(item.abstract_resource_codes),
        )
        for score, item in scored[:top_n]
    ]


# Порог уверенности для выбора между каталогом работ и каталогом материалов
# (и для честного "кандидат не найден") — изначально подобран по факту
# распределения score на двух реальных сметах (кровля №0373100025626000005,
# потолок №0373100025726000259, 2026-09-28): подтверждённые правильные
# совпадения дали score >= 0.50, случайные/ошибочные — <= 0.42.
#
# **Пересмотрен на 0.45, 2026-09-29 (круг 2, вместе с фиксом
# `tokenize_words()` выше)** — снова по факту, не на глаз: прогон обоих
# реальных документов круга 2 БЕЗ гейта threshold (все 42 строки с
# известным эталонным кодом, полный каталог 34004+45847 позиций) показал,
# что распределение сдвинулось вниз. Две реально верные позиции
# («Устройство подстилающих... слоёв оснований: из щебня/из песка»,
# Краснодар) стабильно дают top-1 = правильный код, но со score 0.4615 —
# ниже старого порога 0.50, то есть раньше отвергались бы как "не найдено"
# при заведомо верном ответе. При этом ближайшие СВЕРХУ ошибочные
# совпадения по обоим документам остались на 0.4286 и 0.4167 — ниже новых
# 0.45 с запасом (~0,02-0,03), а подлинный шум (строки вне каталога вообще
# — погрузка/перевозка мусора) — на 0.18-0.30, ниже с большим запасом. 0.45
# — чуть выше верхней границы подтверждённого шума и чуть ниже нижней
# границы подтверждённых верных совпадений, без единого нового ложного
# срабатывания на этих 42 строках.
MATCH_SCORE_THRESHOLD = 0.45


def choose_candidate_source(
    work_candidates: list[RateCandidate],
    material_candidates: list[MaterialRateCandidate],
    threshold: float = MATCH_SCORE_THRESHOLD,
) -> str | None:
    """Какой из двух списков кандидатов использовать для строки ведомости —
    по факту, чему совпадение нашлось увереннее (выше `match_score`), а не
    по эвристике вроде единицы измерения. Возвращает `"work"`, `"material"`
    или `None`.

    `None` — честный случай "кандидат не найден", в двух случаях: (1) оба
    списка пусты; (2) лучший score из обоих каталогов ниже `threshold` —
    низкая уверенность в обоих путях не должна выдаваться как находка
    только потому, что один edge чуть выше другого (например, 0.29 против
    0.21 — оба одинаково не находка)."""
    work_best = work_candidates[0].match_score if work_candidates else -1.0
    material_best = material_candidates[0].match_score if material_candidates else -1.0
    best = max(work_best, material_best)
    if best < threshold:
        return None
    return "work" if work_best >= material_best else "material"


def search_material_candidates(
    catalog: list[MaterialCandidateInfo], query_text: str, top_n: int = 5
) -> list[MaterialRateCandidate]:
    """То же самое, что `search_candidates()`, но по каталогу материалов
    ФСБЦ вместо каталога работ ГЭСН/ГЭСНр. Региональная цена (`unit_price`/
    `price_source`) здесь ещё не посчитана — только `base_price_2022` и
    `match_score`, цену определяет отдельно `pricing.
    price_material_candidates_for_region()`, как и у `RateCandidate`."""
    query_tokens = tokenize_words(query_text)
    if not query_tokens:
        return []

    scored: list[tuple[float, MaterialCandidateInfo]] = []
    for item in catalog:
        item_tokens = tokenize_words(item.name)
        score = _overlap_score(query_tokens, item_tokens)
        if score is None:
            continue
        scored.append((score, item))

    scored.sort(key=lambda pair: pair[0], reverse=True)
    return [
        MaterialRateCandidate(
            code=item.code,
            name=item.name,
            unit=item.unit,
            match_score=score,
            base_price_2022=item.price,
        )
        for score, item in scored[:top_n]
    ]
