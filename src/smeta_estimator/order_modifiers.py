"""Модификаторы условий производства работ из ссылок на пункт приказа в
колонке "Обоснование" — найдено на реальном документе ("потолок", тендер
№0373100025726000259, 2026-09-30, см. CLAUDE.md, открытый п.19).

**Что это и откуда взялось.** Реальный сметчик иногда переиспользует код
ГЭСН не по его прямому назначению — например, применяет МОНТАЖНЫЙ код для
ДЕМОНТАЖНОЙ строки (или наоборот), потому что отдельной демонтажной нормы
для этого вида работ в каталоге нет. Чтобы норма не была явно неверной, он
добавляет отдельной вложенной строкой сразу после позиции ссылку на пункт
приказа Минстроя, задающего понижающий/повышающий коэффициент, и явно
выписывает сами коэффициенты в тексте этой строки — например:

    "421/пр_2020_п.58_пп.б" — "Для работ, при которых выполняемые
    технологические процессы аналогичны технологическим процессам в новом
    строительстве... ОЗП=1,15; ЭМ=1,25 к расх.; ЗПМ=1,25; ТЗ=1,15; ТЗМ=1,25"

    "571/пр_2022_п.83_т.2_стр.3_стб.3" — демонтаж систем инженерно-
    технического обеспечения, ОЗП=0,4; ЭМ=0,4; ЗПМ=0,4; МАТ=0; ТЗ=0,4; ТЗМ=0,4

**Подтверждено как устойчивый паттерн, не единичный случай — на ДВУХ
документах круга 1, не только на "потолке".** На "потолке" — 6 вхождений
"421/пр_2020_п.58_пп.б" (позиции 2, 4, 5, 6, 7, 8) и по одному вхождению
"571/пр_2022_п.83_т.2_стр.3_стб.3"/"...п.84_т.3_стр.1_стб.3" (позиции 2 и
4 соответственно — обе демонтажные, применяются ВМЕСТЕ с 421/пр на одной и
той же позиции: коэффициенты перемножаются, подтверждено числами позиции
"2" — 0,46=1,15×0,4, ровно то значение, что реальный сметчик пишет в
столбце "коэффициенты"). На "roof" (тот же день, проверено ПОСЛЕ первой
версии этого модуля) — тоже нашлась одна ссылка, "571/пр_2022_п.83_т.2_
стр.4_стб.3" (демонтаж фальшфасада из баннерной сетки, тем же монтажным
кодом "ГЭСН08-07-006-01", что и у обратной, монтажной позиции) — то есть
изначальный вывод "на roof ни одной ссылки не встретилось" был ОШИБОЧНЫМ
(сделан до того, как модификаторы вообще были реализованы и прогнаны на
этом документе повторно) — исправлено ниже. Не проверено на документах
круга 2 (Краснодар/МО, "Строительный эксперт") — другая программа
составления смет, формат ссылок может отличаться, если/когда там
встретится такой случай — не факт, что тот же паттерн `\\d+/пр...п.NN`
подойдёт без изменений.

**Найденная и исправленная коллизия — то самое ограничение, о котором
изначально предупреждала первая версия этого докстринга, реально
случилось при первой же проверке на ВТОРОМ документе.** Первая версия
ключа справочника включала только номер приказа и номер пункта
("571/пр.83"), без суффикса "_т.N_стр.M_стб.K" — предполагалось, что
разные коэффициенты всегда различаются номером САМОГО пункта (83 vs 84).
Оказалось не так: пункт 83 сам по себе — ТАБЛИЦА с разными строками,
дающими РАЗНЫЕ коэффициенты в зависимости от того, что демонтируется —
"_т.2_стр.3_стб.3" (демонтаж систем инженерно-технического обеспечения,
0,4, "потолок") и "_т.2_стр.4_стб.3" (демонтаж металлических/композитных
конструкций, 0,7, "roof") — ОБА под одним и тем же "571/пр.83". С ключом
без суффикса позиция "roof" получила бы ЧУЖОЙ коэффициент 0,4 вместо
верного 0,7 — реально произошло бы занижение на этой позиции, если бы это
не было замечено при построчной сверке сразу после первой реализации.
**Исправлено — весь суффикс после "п.NN" теперь часть ключа**
(`normalize_order_reference()` возвращает "571/пр.83_т.2_стр.3_стб.3" и
"571/пр.83_т.2_стр.4_стб.3" как РАЗНЫЕ ключи). Стоимость этого решения —
более узкие, более многочисленные записи справочника (по одному пункту
таблицы, не по всему пункту приказа целиком) — принято как более безопасный
компромисс: ложное "не нашли в справочнике" (честно исключённая позиция,
видна эксперту) лучше, чем тихая подстановка чужого числа.

**Почему берём коэффициенты из справочника, а не парсим текст описания
заново для каждой находки.** Сама ссылка (`"421/пр_2020_п.58_пп.б"`) —
стабильный идентификатор конкретной строки конкретного приказа: одна и та
же ссылка всегда даёт один и тот же коэффициент, а свободный текст
описания рядом ("Для работ, при которых...") может отличаться дословно от
документа к документу даже для той же ссылки. Регулярка по тексту
описания была бы менее надёжной, чем один раз внести коэффициент в
справочник по полной ссылке и дальше использовать его по ключу — тот же
принцип, что уже применён для остальных источников нормативки (Агент 10,
`regulatory_updates`) и для кодов каталога (`code_lookup.py`)."""

from __future__ import annotations

import re
from dataclasses import dataclass, field

_ORDER_REF_RE = re.compile(
    r"(?P<order>\d+)/пр[_\s]*(?:\d{4}[_\s]*)?п\.(?P<point>\d+)(?P<suffix>(?:_[\w.]+)*)",
    re.IGNORECASE,
)


def normalize_order_reference(raw: str) -> str | None:
    """"421/пр_2020_п.58_пп.б" -> "421/пр.58_пп.б". `None` — не похоже на
    ссылку на пункт приказа вообще (обычный код ресурса/каталога, пустая
    строка).

    **Суффикс после "п.NN" (например "_пп.б", "_т.2_стр.3_стб.3") — часть
    ключа, НЕ отбрасывается.** Изначально ключ строился только из номера
    приказа и номера пункта — оказалось недостаточно: найдено на реальных
    данных (roof + ceiling, 2026-09-30, см. CLAUDE.md открытый п.19), что
    ОДИН И ТОТ ЖЕ пункт "571/пр.83" содержит ТАБЛИЦУ с разными строками,
    дающими РАЗНЫЕ коэффициенты в зависимости от того, что демонтируется
    ("_т.2_стр.3_стб.3" — демонтаж систем инженерно-технического
    обеспечения, 0,4; "_т.2_стр.4_стб.3" — демонтаж металлических/
    композитных конструкций, 0,7, обнаружено на документе "roof" уже ПОСЛЕ
    того, как справочник был заведён только по номеру пункта — без этого
    суффикса позиция roof получила бы чужой коэффициент 0,4 вместо верного
    0,7). Без суффикса ("_пп.б"/"_т.N_стр.M_стб.K" отсутствует) — ключ
    остаётся просто "N/пр.NN", как и раньше."""
    if not raw:
        return None
    match = _ORDER_REF_RE.search(raw)
    if not match:
        return None
    return f"{match.group('order')}/пр.{match.group('point')}{match.group('suffix')}"


@dataclass(frozen=True)
class OrderModifier:
    """Множители на КОЛИЧЕСТВО ресурса (не на цену) — ровно то же, что
    реальный сметчик пишет в колонку "коэффициенты" рядом с нормой. По
    категориям ресурса (см. `_resource_category()` в `pricing.py`):
    `ozp` — рабочие (коды "N-100-XX", кроме "4-100-XX"), `em` — машины
    (коды "9X.XX.XX-XXXX"), `zpm` — машинисты (коды "4-100-XX"), `mat` —
    материалы (всё остальное). Приказы также указывают "ТЗ"/"ТЗМ"
    (трудозатраты в чел.-ч) — не хранятся отдельно, потому что во всех
    проверенных на реальных данных случаях ТЗ==ОЗП и ТЗМ==ЗПМ (одна и та же
    величина в стоимостном и трудочасовом выражении, приказы дают их
    парой с одинаковым числом) — см. докстринг модуля."""

    ozp: float = 1.0
    em: float = 1.0
    zpm: float = 1.0
    mat: float = 1.0


# Справочник "ссылка на пункт приказа -> модификатор" — редактируется
# человеком-экспертом по мере появления новых реальных ссылок, без правки
# логики расчёта (`pricing.py` только применяет уже найденный `OrderModifier`,
# не хранит и не угадывает значения). Ключ — ПОЛНАЯ ссылка, включая суффикс
# после "п.NN" ("_пп.б"/"_т.N_стр.M_стб.K") — см. докстринг модуля про
# найденную и исправленную коллизию (два разных значения под одним "571/пр.83"
# без суффикса). Все текущие значения — найдены и подтверждены на реальных
# документах "потолок" и "roof", 2026-09-30.
ORDER_MODIFIER_REGISTRY: dict[str, OrderModifier] = {
    # "Для работ, при которых выполняемые технологические процессы
    # аналогичны технологическим процессам в новом строительстве..."
    # (потолок, позиции 2, 4, 5, 6, 7, 8)
    "421/пр.58_пп.б": OrderModifier(ozp=1.15, em=1.25, zpm=1.25, mat=1.0),
    # "Демонтаж (разборка) систем инженерно-технического обеспечения"
    # (потолок, позиция 2 — демонтаж воздухораспределителя)
    "571/пр.83_т.2_стр.3_стб.3": OrderModifier(ozp=0.4, em=0.4, zpm=0.4, mat=0.0),
    # "Демонтаж (разборка) металлических, металлокомпозитных, композитных
    # конструкций" (roof, позиция 10 — демонтаж фальшфасада из баннерной
    # сетки, тем же кодом "ГЭСН08-07-006-01", что и монтажная позиция 11 —
    # ТОТ ЖЕ пункт 83, что у потолка, но ДРУГАЯ строка таблицы и ДРУГОЙ
    # коэффициент — см. докстринг модуля про коллизию)
    "571/пр.83_т.2_стр.4_стб.3": OrderModifier(ozp=0.7, em=0.7, zpm=0.7, mat=0.0),
    # "Демонтаж оборудования, пригодного для дальнейшего использования,
    # со снятием с места установки, необходимой (частичной) разборкой и
    # консервированием..." (потолок, позиция 4 — демонтаж извещателя ПС;
    # само применение сейчас не влияет на расчёт — позиция всё равно не
    # оценивается из-за отдельного пробела каталога ГЭСНм, см. открытый п.14)
    "571/пр.84_т.3_стр.1_стб.3": OrderModifier(ozp=0.7, em=0.7, zpm=0.7, mat=0.0),
}


@dataclass
class ResolvedOrderModifiers:
    """Итог применения всех найденных ссылок одной позиции сметы.

    `combined` — произведение модификаторов всех РАСПОЗНАННЫХ (найденных в
    справочнике) ссылок, `None` — если распознанных ссылок не было вообще
    (обычная позиция без модификатора, поведение не меняется).
    `matched_references` — сырые строки, которые реально вошли в `combined`
    (для честного вывода в диагностике — `work_volume_extractor.
    _ORDER_REFERENCE_HINT_RE` широкий и попутно ловит ссылки на пункты НР/СП
    ("Пр/812-...", не про модификатор условий вообще), которые здесь тихо
    отбрасываются как "не похоже на `N/пр...п.NN`" — не стоит путать их с
    реально применённым модификатором в логах).
    `unmatched_references` — ссылки, которые ПОХОЖИ на ссылку на пункт
    приказа (прошли `normalize_order_reference()`), но справочник их не
    знает — цена считается БЕЗ модификатора (как раньше), но позиция
    помечается для проверки эксперта (см. `estimate_smeta_document.py`,
    `source="unmatched_modifier_reference"`), не угадывается."""

    combined: OrderModifier | None
    matched_references: list[str] = field(default_factory=list)
    unmatched_references: list[str] = field(default_factory=list)


def resolve_order_modifiers(raw_references: list[str]) -> ResolvedOrderModifiers:
    """Строки, которые вообще не распознаются как ссылка на пункт приказа
    (`normalize_order_reference()` вернул `None`) — тихо игнорируются, не
    попадают ни в `combined`, ни в `matched_references`/`unmatched_references`:
    это не ошибка, просто `work_volume_extractor._ORDER_REFERENCE_HINT_RE` —
    дешёвый широкий фильтр "похоже на ссылку", не точный разбор (например,
    ссылки на пункты НР/СП вида "Пр/812-016.0-1, Приказ № 812/пр от
    21.12.2020 п.25" тоже содержат "N/пр", но не про модификатор условий —
    `normalize_order_reference()` их не матчит, т.к. после "/пр" не следует
    "п.NN" непосредственно)."""
    ozp = em = zpm = mat = 1.0
    matched_any = False
    matched: list[str] = []
    unmatched: list[str] = []
    for raw in raw_references:
        key = normalize_order_reference(raw)
        if key is None:
            continue
        modifier = ORDER_MODIFIER_REGISTRY.get(key)
        if modifier is None:
            unmatched.append(key)
            continue
        matched_any = True
        matched.append(raw)
        ozp *= modifier.ozp
        em *= modifier.em
        zpm *= modifier.zpm
        mat *= modifier.mat
    combined = OrderModifier(ozp=ozp, em=em, zpm=zpm, mat=mat) if matched_any else None
    return ResolvedOrderModifiers(combined=combined, matched_references=matched, unmatched_references=unmatched)
