def test_scans_multiple_tables_independently():
    other_table = [["Наименование работ", "Ед. изм.", "Количество"], ["Демонтаж кровли", "м2", "300"]]
    rows = extract_work_volume_rows([_TYPICAL_TABLE, other_table])
