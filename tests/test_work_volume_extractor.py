def test_fractional_subposition_uses_coefficient_column_not_raw_quantity():
    rows = extract_work_volume_rows([_REAL_LSR_WITH_COEFFICIENTS_TABLE])
    by_code = {row.code: row for row in rows}

    # Щебень: raw "Количество" = 126 (норма на 100 м3 родителя), реальная
    # потребность = 126 × 0.0994 = 12.5244 — уже посчитана составителем
    # сметы в соседней колонке, фикс должен взять именно её.
    assert by_code["02.2.05.04-2088"].quantity == 12.5244
    # Песок — тот же паттерн.
    assert by_code["02.3.01.02-1104"].quantity == 10.934


def test_fractional_subposition_works_when_scaled_quantity_is_larger():
    # Шурупы (9.1): у родителя (9) объём 3.24 — реальная потребность (3.24)
    # БОЛЬШЕ нормы (1), не меньше, как у щебня/песка выше. Фикс не должен
    # быть завязан на направление сравнения.
    rows = extract_work_volume_rows([_REAL_LSR_WITH_COEFFICIENTS_TABLE])
    by_code = {row.code: row for row in rows}
    assert by_code["01.7.15.14-0047"].quantity == 3.24


def test_fractional_subposition_duplicate_resource_code_uses_own_parent():
    # 16.1 и 17.1 — один и тот же код ресурса (12.1.01.05-0047), но разные
    # родители (0.16 и 0.08) — каждая подпозиция должна взять коэффициент
    # СВОЕГО родителя, не спутать с соседней (до фикса обе строки давали
    # одну и ту же сумму 15 493,80 ₽, хотя реальные суммы отличались более
    # чем в 2 раза — см. CLAUDE.md открытый п.17, круг 2).
    rows = extract_work_volume_rows([_REAL_LSR_WITH_COEFFICIENTS_TABLE])
    matches = [row for row in rows if row.code == "12.1.01.05-0047"]
    assert len(matches) == 2
    assert matches[0].quantity == 16.0
    assert matches[1].quantity == 8.0


